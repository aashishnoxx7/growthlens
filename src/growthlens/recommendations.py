"""
Business recommendations engine for GrowthLens.

Generates explainable, data-driven recommendations from analytical results.
Every recommendation is traceable to a calculated metric or finding.

Recommendations are NOT generated by an LLM. They use transparent,
testable business rules applied to the user's selected data.
"""

from __future__ import annotations

import logging
from typing import Any, Optional

import pandas as pd

from growthlens.config import MIN_SEGMENT_SIZE

logger = logging.getLogger(__name__)


def generate_recommendations(
    funnel_df: Optional[pd.DataFrame] = None,
    funnel_findings: Optional[list[dict]] = None,
    acquisition_df: Optional[pd.DataFrame] = None,
    device_df: Optional[pd.DataFrame] = None,
    retention_summary: Optional[dict] = None,
    quality_checks: Optional[list[dict]] = None,
    overall_conversion: Optional[float] = None,
) -> list[dict]:
    """
    Generate prioritized business recommendations from analytical results.

    Each recommendation has:
        id, priority, category, problem, evidence, metric_values,
        affected_segment, recommended_action, expected_direction,
        how_to_test, limitations
    """
    recs: list[dict] = []
    rid = [0]  # mutable counter

    def _add(rec: dict) -> None:
        rid[0] += 1
        rec["id"] = rid[0]
        recs.append(rec)

    # ── Pattern A: Funnel drop-off ────────────────────────────────────────────
    if funnel_findings:
        for f in funnel_findings:
            if f["type"] == "funnel_drop":
                ev = f["evidence"]
                _add({
                    "priority": "High",
                    "category": "Funnel Optimization",
                    "problem": (
                        f"Large session drop-off after '{ev['stage']}' "
                        f"({ev['dropoff_abs']:,} sessions, {ev['dropoff_pct']:.1f}%)."
                    ),
                    "evidence": f["message"],
                    "metric_values": {
                        "dropoff_abs": ev["dropoff_abs"],
                        "dropoff_pct": ev["dropoff_pct"],
                        "stage": ev["stage"],
                    },
                    "affected_segment": "All sessions",
                    "recommended_action": (
                        f"Audit the user experience at the '{ev['stage']}' step. "
                        "Review session recordings, form-error logs, and page-load performance. "
                        "Consider an A/B test of an improved flow."
                    ),
                    "expected_direction": (
                        "Hypothesis: reducing friction at this stage increases sessions "
                        "proceeding to the next funnel step. Direction of impact uncertain "
                        "until root cause is confirmed."
                    ),
                    "how_to_test": (
                        "Implement the change for a subset of users. Measure the step-to-step "
                        "conversion rate for the treatment group vs control over ≥2 business cycles. "
                        "Use the Experiment Lab to estimate required sample size."
                    ),
                    "limitations": (
                        "Observed drop-off reflects session counts, not user intent. "
                        "The cause may be UX friction, traffic intent, or tracking gaps."
                    ),
                })

    # ── Pattern B: Segment performance ───────────────────────────────────────
    if device_df is not None and not device_df.empty and overall_conversion is not None:
        for _, row in device_df.iterrows():
            if (
                row["sessions"] >= MIN_SEGMENT_SIZE and
                row["conversion_rate_pct"] < overall_conversion * 100 * 0.75 and
                not row.get("low_sample", False)
            ):
                _add({
                    "priority": "Medium",
                    "category": "Device Experience",
                    "problem": (
                        f"{row['device_category'].title()} sessions convert at "
                        f"{row['conversion_rate_pct']:.1f}% vs overall {overall_conversion*100:.1f}%."
                    ),
                    "evidence": (
                        f"{int(row['sessions']):,} {row['device_category']} sessions observed. "
                        f"Conversion rate is {(overall_conversion*100 - row['conversion_rate_pct']):.1f} pp below average."
                    ),
                    "metric_values": {
                        "device": row["device_category"],
                        "sessions": int(row["sessions"]),
                        "device_conversion_pct": float(row["conversion_rate_pct"]),
                        "overall_conversion_pct": round(overall_conversion * 100, 2),
                    },
                    "affected_segment": f"{row['device_category'].title()} users",
                    "recommended_action": (
                        f"Audit the {row['device_category']} experience end-to-end. "
                        "Test checkout flow, page load speed, and form usability on real devices."
                    ),
                    "expected_direction": (
                        "Hypothesis: improving the mobile/tablet experience increases "
                        "conversion for that device segment."
                    ),
                    "how_to_test": (
                        "Run a device-targeted experiment after fixing the experience. "
                        "Monitor device-segmented conversion rate and funnel drop-off."
                    ),
                    "limitations": (
                        "Device-level differences may reflect user intent, not solely UX quality. "
                        "Validate whether the traffic mix differs before attributing the gap to UX."
                    ),
                })

    # ── Pattern C: Acquisition quality ────────────────────────────────────────
    if acquisition_df is not None and not acquisition_df.empty and overall_conversion is not None:
        for _, row in acquisition_df.head(10).iterrows():
            if (
                row["sessions"] >= MIN_SEGMENT_SIZE * 3 and
                row["conversion_rate_pct"] < overall_conversion * 100 * 0.6
            ):
                src = f"{row.get('traffic_source', '?')} / {row.get('traffic_medium', '?')}"
                _add({
                    "priority": "Medium",
                    "category": "Acquisition Quality",
                    "problem": (
                        f"High-volume channel '{src}' shows low conversion "
                        f"({row['conversion_rate_pct']:.1f}% vs {overall_conversion*100:.1f}% overall)."
                    ),
                    "evidence": (
                        f"{int(row['sessions']):,} sessions from '{src}'. "
                        f"Only {int(row['sessions_purchase'])} resulted in a purchase."
                    ),
                    "metric_values": {
                        "source_medium": src,
                        "sessions": int(row["sessions"]),
                        "purchases": int(row["sessions_purchase"]),
                        "channel_conversion": float(row["conversion_rate_pct"]),
                        "overall_conversion": round(overall_conversion * 100, 2),
                    },
                    "affected_segment": src,
                    "recommended_action": (
                        "Review the landing page and user intent for this channel. "
                        "Assess whether messaging aligns with purchase-intent audiences. "
                        "Investigate whether event tracking is complete for this source."
                    ),
                    "expected_direction": (
                        "Hypothesis: improving landing-page relevance and audience targeting "
                        "increases conversion from this channel."
                    ),
                    "how_to_test": (
                        "Implement landing-page or targeting changes and measure conversion rate "
                        "before/after. Note: without advertising spend data, ROI cannot be assessed."
                    ),
                    "limitations": (
                        "GA4 first-user attribution may not reflect the session that drove the purchase. "
                        "Advertising spend and ROAS data are not available in this dataset."
                    ),
                })

    # ── Pattern D: Data quality impact ────────────────────────────────────────
    if quality_checks:
        errors = [c for c in quality_checks if c["severity"] == "error" and c["status"] != "pass"]
        for check in errors[:2]:  # Limit to top 2 errors
            _add({
                "priority": "High",
                "category": "Data Quality",
                "problem": f"Data quality issue: {check['check_name']}.",
                "evidence": check["message"],
                "metric_values": {
                    "affected_rows": check["affected_rows"],
                    "pct_affected": check["pct_affected"],
                },
                "affected_segment": "All data",
                "recommended_action": check["remediation"],
                "expected_direction": (
                    "Fixing this issue will increase confidence in reported metrics."
                ),
                "how_to_test": (
                    "Rerun quality checks after the fix is applied. Verify affected counts drop to zero."
                ),
                "limitations": (
                    "Root cause may require changes to GA4 instrumentation or data pipeline."
                ),
            })

    if not recs:
        logger.info("No recommendations generated — data may not meet minimum thresholds.")

    return recs
